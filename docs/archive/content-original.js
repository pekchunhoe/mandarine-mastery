export function sentenceChunks(item) {
  const text = practiceExample(item),
    manual = phrases[item.word];
  if (manual?.join('') === text) return manual;
  const clauses = text.match(/[^，。！？；：]+[，。！？；：]?/g) || [text];
  if (clauses.length >= 2) return clauses;
  const subjects = [
    '远处有一艘白色帆船',
    '这本童话的作者',
    '爷爷',
    '奶奶',
    '妈妈',
    '爸爸',
    '妹妹',
    '姐姐',
    '哥哥',
    '弟弟',
    '叔叔',
    '阿姨',
    '老师',
    '校长',
    '记者',
    '护士',
    '我们小组',
    '同学们',
    '值日生',
    '那位善良的阿姨',
    '几个孩子',
    '小兔',
    '小猴',
    '小狗',
    '海军',
    '军人',
    '政府',
    '我们',
    '我',
    '他',
    '她',
  ];
  const subject = subjects.find(
    (s) =>
      text.startsWith(s) &&
      text.length > s.length + 4 &&
      !/^[的们和与、或]/.test(text.slice(s.length)) &&
      !(['我', '他'].includes(s) && /^[国人家]/.test(text.slice(s.length))),
  );
  return subject ? [subject, text.slice(subject.length)] : null;
}

